import { readFileSync, writeFileSync, copyFileSync } from 'node:fs'
import { createRequire } from 'node:module'
const require = createRequire(import.meta.url)
const root = new URL('../', import.meta.url)
const packageRoot = new URL('./', `file://${require.resolve('framework7-icons/package.json')}`)
const icons = JSON.parse(readFileSync(new URL('scripts/framework7-icons.json', root), 'utf8'))
const readSvg = (name) => {
  const svg = readFileSync(new URL(`svg/${name}.svg`, packageRoot), 'utf8')
  return svg.trim().replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '').replaceAll('fill-rule=', 'fillRule=').replaceAll('clip-rule=', 'clipRule=')
}
let source = `// Generated by scripts/generate-framework7-icons.mjs from Framework7 Icons 5.0.5 (MIT).
import { forwardRef, type ReactNode, type SVGProps } from 'react'

export type IconProps = Omit<SVGProps<SVGSVGElement>, 'ref'> & {
  size?: number | string
  weight?: 'thin' | 'light' | 'regular' | 'bold' | 'fill' | 'duotone'
  mirrored?: boolean
  title?: string
}

function createIcon(name: string, outline: ReactNode, filled: ReactNode = outline) {
  const IconComponent = forwardRef<SVGSVGElement, IconProps>(function Framework7Icon(
    { size = '1em', weight, mirrored, title, children, style, ...props }, ref,
  ) {
    return <svg ref={ref} xmlns="http://www.w3.org/2000/svg" viewBox="0 0 56 56" width={size} height={size} fill="currentColor" focusable="false"
      aria-hidden={props['aria-label'] || props['aria-labelledby'] || title ? undefined : true}
      role={title ? 'img' : undefined} {...props}
      style={mirrored ? { ...style, transform: [style?.transform, 'scaleX(-1)'].filter(Boolean).join(' ') } : style}>
      {title ? <title>{title}</title> : null}{weight === 'fill' ? filled : outline}{children}
    </svg>
  })
  IconComponent.displayName = name
  return IconComponent
}

export type Icon = ReturnType<typeof createIcon>

`
for (const [name, glyph] of Object.entries(icons)) {
  let filled = ''
  try { filled = `, <>${readSvg(`${glyph}_fill`)}</>` } catch (error) { if (error.code !== 'ENOENT') throw error }
  source += `export const ${name} = createIcon('${name}', <>${readSvg(glyph)}</>${filled})\n`
}
writeFileSync(new URL('src/icons.tsx', root), source)
copyFileSync(new URL('LICENSE', packageRoot), new URL('FRAMEWORK7-ICONS-LICENSE', root))
